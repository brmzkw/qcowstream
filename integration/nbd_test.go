package integration

import (
	"fmt"
	"strings"
	"testing"
)

// serve starts qemu-nbd on a Unix socket for the image, read-only, accepting
// several clients, and returns a command that stops it.
func serve(dir, sock, image string, extra ...string) string {
	return fmt.Sprintf("qemu-nbd --fork --persistent --shared=16 --read-only --pid-file=%[1]s/%[2]s.pid -k %[1]s/%[2]s -x scsi0 -f qcow2 %[4]s %[3]s",
		dir, sock, image, strings.Join(extra, " "))
}

func stop(dir, sock string) string {
	return fmt.Sprintf("kill $(cat %[1]s/%[2]s.pid); while [ -e %[1]s/%[2]s ]; do sleep 0.05; done", dir, sock)
}

// TestQemuNBDBitmapChain exports a disk with qemu-nbd, takes a full image,
// then an incremental one from a 4 MiB persistent dirty bitmap (the Proxmox
// granularity), each generated by the CLI inside the container, the
// incremental one in a directory without its parent.
func TestQemuNBDBitmapChain(t *testing.T) {
	each(t, func(t *testing.T, e *qemuEnv) {
		e.installCLI(t)
		d := e.dir(t)
		e.run(t, fmt.Sprintf(`cd %[1]s
qemu-img create -q -f qcow2 src.qcow2 64M
qemu-io -c 'write -P 0xaa 0 4M' -c 'write -P 0xbb 20M 2M' -c 'write -P 0x11 40M 8M' src.qcow2 >/dev/null
%[2]s
qcowstream full --nbd-socket %[1]s/full --export scsi0 --output base.qcow2
qcowstream full --nbd-socket %[1]s/full --export scsi0 --no-zero-detection --concurrency 4 --output - | cat > base-nozero.qcow2
%[3]s
qemu-img convert -O raw src.qcow2 want0.raw
qemu-img check -q base.qcow2 && qemu-img check -q base-nozero.qcow2
qemu-img convert -O raw base.qcow2 got.raw && cmp got.raw want0.raw
qemu-img convert -O raw base-nozero.qcow2 got.raw && cmp got.raw want0.raw
test $(stat -c %%s base.qcow2) -lt $(stat -c %%s base-nozero.qcow2)

qemu-img bitmap --add -g 4M src.qcow2 backup
qemu-io -c 'write -P 0xcc 8M 4M' -c 'write -z 20M 2M' -c 'write -P 0xdd 41M 64K' -c 'write -P 0xee 63M 1M' src.qcow2 >/dev/null
%[4]s
mkdir gen
cd gen
qcowstream plan incremental --nbd-socket %[1]s/inc --export scsi0 --bitmap backup --backing-file base.qcow2 > plan.json
qcowstream incremental --nbd-socket %[1]s/inc --export scsi0 --bitmap backup --backing-file base.qcow2 --concurrency 4 --output inc-1.qcow2
ls
qemu-img check 'json:{"driver":"qcow2","backing":null,"file":{"driver":"file","filename":"inc-1.qcow2"}}' >/dev/null
cd ..
%[5]s
mv gen/inc-1.qcow2 .
qemu-img convert -O raw src.qcow2 want1.raw
qemu-img convert -O raw inc-1.qcow2 got.raw && cmp got.raw want1.raw
qemu-img info --backing-chain inc-1.qcow2 | grep '^image:'
`, d, serve(d, "full", "src.qcow2"), stop(d, "full"), serve(d, "inc", "src.qcow2", "-B backup"), stop(d, "inc")))

		listing := e.run(t, "ls "+d+"/gen")
		if strings.Contains(listing, "base") {
			t.Fatalf("the parent was present during generation: %s", listing)
		}
		plan := e.run(t, "cat "+d+"/gen/plan.json")
		// 8M-12M, 20M-22M (rounded to the 4 MiB bitmap: 20M-24M), 40M-44M, 60M-64M.
		for _, want := range []string{`"cluster_size": 2097152`, `"backing_file": "base.qcow2"`} {
			if !strings.Contains(plan, want) {
				t.Fatalf("plan lacks %s:\n%s", want, plan)
			}
		}
	})
}

func TestQemuNBDMissingBitmap(t *testing.T) {
	each(t, func(t *testing.T, e *qemuEnv) {
		e.installCLI(t)
		d := e.dir(t)
		e.run(t, fmt.Sprintf("cd %s && qemu-img create -q -f qcow2 src.qcow2 16M && qemu-img bitmap --add src.qcow2 backup && %s",
			d, serve(d, "s", "src.qcow2", "-B backup")))
		out := e.fails(t, fmt.Sprintf("cd %s && qcowstream incremental --nbd-socket %s/s --export scsi0 --bitmap nosuch --backing-file base.qcow2 --output inc.qcow2", d, d))
		if !strings.Contains(out, "meta context not available") {
			t.Fatalf("unexpected error: %s", out)
		}
		e.run(t, fmt.Sprintf("cd %s && test ! -e inc.qcow2 && %s", d, stop(d, "s")))
	})
}
